import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile,rm,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import os from 'node:os';
import path from 'node:path';
import {embedProgramTimelineCopy} from './program.js';
const hash=b=>createHash('sha256').update(b).digest('hex');
const md5=b=>createHash('md5').update(b).digest('hex');
test('embeds standalone and show donor roots with guarded replacement and atomic failures',async t=>{
 const dir=await mkdtemp(path.join(os.tmpdir(),'embed-program-'));t.after(()=>rm(dir,{recursive:true,force:true}));
 const source=path.join(dir,'in.skpr'),donor=path.join(dir,'in.sktl'),show=path.join(dir,'in.skshow'),out=path.join(dir,'out.skpr');
 const program=Buffer.from('\ufeff<?xml version="1.0"?><skprogram version="1"><item start="1" name="A" notes=""><graph id="x"/></item><item start="2" name="B" notes="" /></skprogram>');
 const root='<sktimeline version="1"><layers/><audio path="x"/></sktimeline>';
 const timeline=Buffer.from('\ufeff<?xml version="1.0"?>\n'+root+'\n');
 const wrapper=Buffer.from(`<skshow><part name="content/a.sktl" md5="${md5(timeline)}">${timeline.toString('base64')}</part></skshow>`);
 await Promise.all([writeFile(source,program),writeFile(donor,timeline),writeFile(show,wrapper)]);
 const args={source,destination:out,sha256:hash(program),index:0,donor,donorSha256:hash(timeline)};
 const result=await embedProgramTimelineCopy(args);assert.equal(result.items[0].hasTimeline,true);
 assert.equal(await readFile(out,'utf8'),program.toString().replace('</item>',root+'</item>'));
 const second=path.join(dir,'second.skpr');await embedProgramTimelineCopy({...args,destination:second,index:1,donor:show,donorSha256:hash(wrapper),donorName:'content/a.sktl'});
 assert.ok((await readFile(second,'utf8')).includes(`<item start="2" name="B" notes="" >${root}</item>`));
 const outBytes=await readFile(out);const guarded={...args,source:out,sha256:hash(outBytes),destination:path.join(dir,'guard.skpr')};
 await assert.rejects(embedProgramTimelineCopy(guarded),/already has/);
 await embedProgramTimelineCopy({...guarded,replaceExisting:true});
 await assert.rejects(embedProgramTimelineCopy({...args,destination:path.join(dir,'bad.skpr'),sha256:'0'.repeat(64)}),/Program changed/);
 await assert.rejects(embedProgramTimelineCopy({...args,destination:path.join(dir,'bad.skpr'),donorSha256:'0'.repeat(64)}),/Donor changed/);
 await assert.rejects(embedProgramTimelineCopy(args),{code:'EEXIST'});assert.deepEqual(await readFile(out),outBytes);
 await writeFile(donor,'<sktimeline version="2"/>');await assert.rejects(embedProgramTimelineCopy({...args,destination:path.join(dir,'bad.skpr'),donorSha256:hash(Buffer.from('<sktimeline version="2"/>'))}),/version 1/);
 assert.ok(!(await readdir(dir)).some(n=>n.endsWith('.tmp')));
});
